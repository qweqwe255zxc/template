import type { CSSProperties } from "react";

/**
 * Пониженный потолок --size-h1: 64px → 52px.
 *
 * Нужен любой раскладке, где заголовок живёт не во всю ширину страницы, а
 * в колонке примерно на половину (split, showcase, billboard). При полном
 * потолке базовый кегль не оставляет места двум словам в одной ручной
 * строке, и она переносится сама — второй уровень переноса поверх
 * авторского, из-за которого заголовок расползается на лишние строки и
 * выдавливает кнопки за первый экран.
 *
 * --size-h1 — обычная CSS-переменная, поэтому override живёт в
 * поддереве заголовка и не трогает токен глобально: type-only, centered,
 * Team и страница 404 продолжают верстаться полным кеглем.
 *
 * Лежит отдельным модулем, а не в HeroLede: billboard рисует свой
 * заголовок (на акцентной панели правило «последняя строка акцентом»
 * не работает — акцент по акценту не виден), но ту же ступень обязан
 * брать отсюда, а не заводить второе значение.
 */
/* Инвариант: строго ниже глобального --size-h1 на любой ширине —
   @768 41 vs 51, @1024 45 vs 63, @1440 52 vs 64. Если правишь одно
   значение, пересчитывай второе: при потолке выше глобального ступень
   инвертируется и «пониженный» кегль становится крупнее обычного.

   Потолок выбран по МЕРЕ СТРОКИ, а не под конкретный заголовок: колонка
   split/showcase на широком экране — около 670px, и 52px дают там ~21
   знак в строке. Не подгоняй это число под текущий текст демо: у клиента
   заголовок другой, а мера остаётся. */
export const COMPACT_H1 = {
  "--size-h1": "clamp(2.125rem, 1.73rem + 1.69vw, 3.25rem)",
} as CSSProperties;

/**
 * ПОДНЯТЫЙ потолок --size-h1: 64px → 104px. Зеркальная COMPACT_H1
 * ступень — и заводится тем же способом (переменная в поддереве
 * заголовка, а не правка токена), чтобы остальные раскладки её не
 * увидели.
 *
 * Нужна ровно одной раскладке — `editorial`, где заголовок занимает всю
 * ширину контейнера (второй колонки в первом экране нет вовсе) и набран
 * в верхнем регистре. На полной ширине 1600px базовые 64px читаются как
 * обычный заголовок раздела, а не как афиша: именно кегль отличает этот
 * первый экран от `type-only`, раскладка у них почти одинаковая.
 *
 * Инвариант: строго ВЫШЕ глобального --size-h1 на любой ширине —
 * @390 41 vs 34, @768 63 vs 51, @1024 79 vs 63, @1440 104 vs 64. Если
 * правишь одно значение, пересчитывай второе: при потолке ниже
 * глобального ступень инвертируется и «поднятый» кегль станет мельче
 * обычного.
 *
 * Потолок выбран по МЕРЕ СТРОКИ: заголовок в этой раскладке идёт с
 * max-w-[14ch], и на контейнере 1600px 104px в верхнем регистре дают
 * ~900px — заметно уже колонки, то есть строка рвётся там, где её
 * разорвал автор массива headline, а не там, где кончилось место.
 */
export const EDITORIAL_H1 = {
  "--size-h1": "clamp(2.5rem, 1.1rem + 6vw, 6.5rem)",
} as CSSProperties;
