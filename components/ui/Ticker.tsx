import type { CSSProperties } from "react";
import { cn } from "@/lib/cn";

interface TickerProps {
  /** Фраза, которая бежит по полосе. Повторяется столько раз, сколько влезает. */
  text: string;
  /** Куда едет лента. Влево по умолчанию. */
  direction?: "left" | "right";
  /** Длительность одной полной петли, секунды. */
  speed?: number;
  className?: string;
}

/** Сколько раз фраза печатается в одной половине ленты. */
const REPEAT = 6;

/**
 * Бегущая строка — второй несущий приём семейства `market` после
 * кричащего заголовка в `MarketHeader`.
 *
 * Что это. Полоса во всю ширину ОКНА (поэтому рисуется вне
 * `Container`), волосяные линейки сверху и снизу, короткая фраза
 * капслоком, повторённая с широкими промежутками и едущая по кругу. В
 * исходном приёме это прямо названо «текстурой бренда»: страница держит
 * ритм не линейками и не карточками, а тремя такими полосами между
 * разделами.
 *
 * Как устроена петля. Внутри ДВЕ одинаковые половины, и анимируется их
 * общая дорожка на -50%, то есть ровно на одну половину: к концу цикла
 * вторая копия стоит там, где в начале стояла первая, и стык не виден.
 * JS в этом не участвует вовсе.
 *
 * `min-w-[100vw]` у каждой половины — не украшение, а условие
 * бесшовности. Без него короткая фраза («Кейсы!») на широком экране даёт
 * дорожку уже двух экранов, и после -50% в полосе открывается пустое
 * место. Половина не бывает уже окна, а `justify-around` раскладывает
 * повторы по ней равномерно — обе половины при этом всё так же
 * одинаковы, и -50% остаётся точным.
 *
 * Именно `100vw`, а не `min-w-full`: процент считается от ширины
 * дорожки, а ширина дорожки — от содержимого половин, то есть от
 * процента. Браузер такую петлю разрывает по-своему, и дорожка
 * схлопывалась до одной половины вместо двух (замерено). Ширина окна —
 * величина, ни от чего в этом узле не зависящая, и петли не создаёт;
 * полоса и так идёт во всю ширину окна, так что значение то же самое.
 *
 * Доступность. Вторая половина `aria-hidden`: фраза должна прозвучать
 * один раз, а не шесть. Движение выключается при
 * `prefers-reduced-motion` (правило в globals.css) — замершая полоса
 * остаётся читаемой, это просто строка повторов.
 *
 * Цвет. Линейки — `border-accent-border`, тот же токен, что держит штрих
 * семейства `atelier`, и по той же причине: на тёмном блоке и на
 * акцентной заливке чистый `--accent` пропадает. Текст под этими же
 * поверхностями уходит в `text-fg` — сплошной цвет текста поверхности,
 * без прозрачности.
 */
export function Ticker({
  text,
  direction = "left",
  speed = 26,
  className,
}: TickerProps) {
  const half = (hidden: boolean) => (
    <div
      // aria-hidden на самой половине, а не на обёртке вокруг неё: лишний
      // флекс-элемент в дорожке пришлось бы отдельно защищать от сжатия.
      aria-hidden={hidden || undefined}
      className="flex min-w-[100vw] shrink-0 items-center justify-around gap-12 md:gap-20"
    >
      {Array.from({ length: REPEAT }, (_, index) => (
        <span key={index}>{text}</span>
      ))}
    </div>
  );

  return (
    <div
      className={cn(
        "flex overflow-hidden border-y border-accent-border py-3 md:py-4",
        "font-heading text-h4 uppercase tracking-[0.04em] whitespace-nowrap select-none",
        "text-accent [[data-surface=accent]_&]:text-fg [[data-surface=ink]_&]:text-fg",
        className,
      )}
      style={{ "--ticker-duration": `${speed}s` } as CSSProperties}
    >
      {/* w-max у дорожки — условие бесшовности, а не подстраховка.
          `translateX(-50%)` считается от ширины САМОЙ дорожки, поэтому
          она обязана быть ровно суммой двух половин. Без явной
          max-content ширины дорожка — обычный флекс-элемент полосы и
          ужимается: замерено, при двух половинах по 5540px она была
          5540, и за полный цикл лента уезжала на 2770px, то есть на
          четверть нужного, — стык становился виден каждый оборот. */}
      <div className="ui-ticker-track flex w-max shrink-0" data-direction={direction}>
        {half(false)}
        {half(true)}
      </div>
    </div>
  );
}

/**
 * Отступы, которые `Section` кладёт снизу, — по одному на каждое
 * значение её пропа `spacing`. Литеральные строки в таблице по той же
 * причине, что в lib/gridFill.ts: сканер Tailwind ищет кандидатов по
 * тексту исходника и склеенное в рантайме `-mb-${x}` не увидит.
 */
const PULL: Record<"section" | "hero" | "lg", string> = {
  section: "-mb-section",
  hero: "-mb-hero",
  lg: "-mb-section-lg",
};

/**
 * Бегущая строка у НИЖНЕГО края секции — та обёртка, в которой её
 * ставят все двенадцать вариантов семейства `market`.
 *
 * Зачем отдельным компонентом. Полоса обязана садиться ВСТЫК к
 * следующему разделу, иначе между ней и ним остаётся полоса фона в
 * половину экрана и отбивка перестаёт читаться отбивкой. Для этого
 * нижний отступ секции съедается отрицательным полем ровно на свою
 * величину — и величина эта зависит от `spacing` секции, то есть её
 * легко перепутать. Двенадцать копий этой арифметики разошлись бы на
 * первой же правке.
 *
 * Значения берутся из тех же токенов, что и сами отступы, поэтому
 * §1.5 п. 3 (никаких фиксированных размеров) не нарушается: поедет
 * токен — поедет и подтяжка.
 */
export function SectionTicker({
  text,
  spacing = "section",
  direction,
}: {
  text: string;
  /** Каким `spacing` живёт секция, в которую ставится полоса. */
  spacing?: "section" | "hero" | "lg";
  direction?: "left" | "right";
}) {
  return (
    <div className={cn("mt-14 md:mt-20", PULL[spacing])}>
      <Ticker text={text} direction={direction} />
    </div>
  );
}

export default Ticker;
