import type { ReactNode } from "react";
import { cn } from "@/lib/cn";

interface SeamGridProps {
  children: ReactNode;
  /**
   * Тег обёртки. По умолчанию `div`; `dl` нужен там, где клетки — это
   * пары «значение — подпись» (цифры, реквизиты): `dt`/`dd` обязаны
   * лежать внутри списка определений, иначе разметка невалидна, а
   * скринридер читает их как обычный текст.
   */
  as?: "div" | "dl" | "ul";
  /** Классы сетки: число колонок по брейкпоинтам. Всё остальное задано тут. */
  className?: string;
}

/**
 * Решётка на волосяных швах — второй несущий приём семейства `atelier`
 * после штриха в `AtelierHeader`.
 *
 * Как это устроено. Сетка красится цветом ЛИНИИ и раздвигает ячейки на
 * один пиксель (`gap-px`), а каждая ячейка закрашивается фоном секции
 * (`SEAM_CELL`). Видимой остаётся ровно та полоска подложки, которая
 * попала в зазор, — то есть линия рисуется не границами ячеек, а
 * просветом между ними. Внешняя рамка замыкает решётку по периметру.
 *
 * Зачем так, а не `border` у каждой ячейки. Границы соседних ячеек
 * складываются в двухпиксельную линию внутри и однопиксельную по краю,
 * и решётка перестаёт быть равномерной; убирать удвоение приходится
 * условными `border-l-0` по индексу — ровно тем кодом, который в
 * `Stats/editorial` занимает половину файла. Здесь индекс ячейки не
 * нужен вовсе: сколько бы их ни было и как бы они ни переносились на
 * следующий ряд, шов всегда один пиксель.
 *
 * Чем отличается от линеек `editorial`. Там линия ОТКРЫТАЯ и её
 * толщина несёт смысл (сплошная — счёт, волосяная — перечень); здесь
 * решётка ЗАМКНУТАЯ и однородная, и смысл несёт не толщина, а сама
 * клетка: блок читается как разграфлённый бланк. Смешивать два приёма
 * в одной секции нельзя — они конкурируют за одну и ту же роль.
 *
 * Ограничение, о котором надо знать: `bg-bg` у ячейки — это фон ТЕКУЩЕЙ
 * поверхности. Если внутрь ячейки нужен другой фон (выделенный тариф
 * акцентной заливкой в `Pricing/atelier`), у неё просто ставится свой
 * `bg-*` вместо `SEAM_CELL` — шов от этого не страдает, он снаружи.
 */
export function SeamGrid({ children, as: Tag = "div", className }: SeamGridProps) {
  return (
    <Tag className={cn("grid gap-px border border-rule bg-rule", className)}>
      {children}
    </Tag>
  );
}

/**
 * Классы ячейки решётки. Отдельной константой, а не компонентом-ячейкой:
 * ячейки в разных секциях — это разные теги (`div` в шагах, `<div>`
 * внутри `<dl>` в цифрах, колонка тарифа с `flex-col`), и оборачивать их
 * в лишний слой значило бы ломать `dl`/`dt`/`dd` и `mt-auto` у кнопки.
 */
export const SEAM_CELL = "bg-bg p-7 md:p-9";

/** То же, но с меньшим внутренним воздухом — для реквизитов и коротких пар. */
export const SEAM_CELL_SM = "bg-bg p-6";

/**
 * Сколько колонок дать решётке под данное число клеток.
 *
 * Растянутая хвостовая клетка (`seamTailSpan`) закрывает остаток, но
 * чем больше остаток, тем сильнее она отличается от соседей: четыре
 * отзыва в три колонки дают последнюю клетку ВТРОЕ шире прочих, и ряд
 * равноправных читается как ряд с выделенным. Поэтому сначала пробуем
 * подобрать число колонок, на которое клетки делятся нацело, и только
 * если не выходит — оставляем максимум и закрываем остаток хвостом.
 *
 * Опускаемся не ниже чем на одну колонку от максимума: восемь клеток
 * делятся на 2, но четыре ряда по две — это уже другая раскладка, а не
 * поправка к этой.
 */
export function seamColumns(count: number, max: number): number {
  if (count <= 1) return 1;
  if (count < max) return count;
  if (count % max === 0) return max;
  const one = max - 1;
  if (one >= 2 && count % one === 0) return one;
  return max;
}

type SeamPrefix = "sm:" | "md:" | "lg:";

/**
 * Классы растяжения ПОСЛЕДНЕЙ клетки на остаток ряда. Литеральные
 * строки в лукап-таблице по той же причине, что в lib/gridFill.ts:
 * сканер Tailwind ищет кандидатов по тексту исходника и склеенное в
 * рантайме `lg:col-span-${n}` не увидит.
 */
const TAIL_SPAN: Record<SeamPrefix, Record<number, string>> = {
  "sm:": { 2: "sm:col-span-2" },
  "md:": { 2: "md:col-span-2", 3: "md:col-span-3" },
  "lg:": { 2: "lg:col-span-2", 3: "lg:col-span-3", 4: "lg:col-span-4" },
};

/**
 * Закрывает неполный последний ряд решётки, растягивая последнюю клетку
 * на весь остаток.
 *
 * Зачем отдельно от `lib/gridFill.ts`. Тот растягивает несколько
 * карточек по +1 и оставляет ряд неполным, если слотов больше, чем
 * карточек (5 карточек в 4 колонки: последняя становится col-span-2, два
 * слота остаются пустыми). В сетке с зазором пустой слот — это просто
 * воздух, и его не видно. В замкнутой решётке на его месте остаётся
 * прямоугольник ЦВЕТА ЛИНИИ внутри рамки, то есть заметная дыра в
 * бланке. Поэтому здесь остаток закрывается всегда и целиком — одной
 * клеткой, а не распределяется по нескольким.
 *
 * Возвращает undefined для всех клеток, кроме последней, и для случая,
 * когда ряд и так полный.
 */
export function seamTailSpan(
  index: number,
  count: number,
  cols: number,
  prefix: SeamPrefix,
): string | undefined {
  if (index !== count - 1) return undefined;

  const remainder = count % cols;
  if (remainder === 0) return undefined;

  return TAIL_SPAN[prefix][cols - remainder + 1];
}

export default SeamGrid;
